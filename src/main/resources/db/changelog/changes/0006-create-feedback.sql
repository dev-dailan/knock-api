CREATE TABLE IF NOT EXISTS feedback_user_answer
(
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    app_type        VARCHAR(20)  NOT NULL,
    question_id     BIGINT       NOT NULL,
    option_id       BIGINT,
    note            VARCHAR(200),
    reference_id    BIGINT,
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    created_by      VARCHAR(100) NOT NULL,
    CONSTRAINT fk_feedback_user_answer_question FOREIGN KEY (question_id) REFERENCES feedback_question (id),
    CONSTRAINT fk_feedback_user_answer_option FOREIGN KEY (option_id) REFERENCES feedback_option (id),
    -- 기타를 선택하면 option_id 가 NULL 이고 의견이 있어야 한다. 선택지를 고르면 의견을 받지 않는다.
    CONSTRAINT ck_feedback_user_answer_note CHECK (
        (option_id IS NOT NULL AND note IS NULL)
            OR (option_id IS NULL AND note IS NOT NULL AND TRIM(note) <> '')
        )
);
COMMENT ON TABLE feedback_user_answer IS '피드백 사용자 응답';
COMMENT ON COLUMN feedback_user_answer.app_type IS '응답한 앱';
COMMENT ON COLUMN feedback_user_answer.question_id IS '피드백 질문 테이블 아이디';
COMMENT ON COLUMN feedback_user_answer.option_id IS '피드백 선택지 테이블 아이디. 기타를 선택하면 NULL';
COMMENT ON COLUMN feedback_user_answer.note IS '사용자가 직접 작성한 의견. 기타를 선택하면 필수, 선택지를 고르면 NULL';
COMMENT ON COLUMN feedback_user_answer.created_by IS '응답한 기기 아이디';

CREATE INDEX ix_feedback_user_answer_question ON feedback_user_answer (question_id);
CREATE INDEX ix_feedback_user_answer_option ON feedback_user_answer (option_id);
