CREATE TABLE letter
(
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sender_device_id VARCHAR(100) NOT NULL,
    send_type        VARCHAR(10)  NOT NULL,
    locale           VARCHAR(10),
    addressee_name   VARCHAR(50),
    content          TEXT         NOT NULL,
    is_activated     BOOLEAN      NOT NULL DEFAULT true,
    is_deleted       BOOLEAN      NOT NULL DEFAULT false,
    created_at       TIMESTAMPTZ  NOT NULL DEFAULT now(),
    created_by       VARCHAR(100) NOT NULL,
    updated_at       TIMESTAMPTZ,
    updated_by       VARCHAR(100)
);
COMMENT ON TABLE letter IS '사용자가 보낸 편지. 다른 사용자에게 랜덤 배달되는 편지 풀';
COMMENT ON COLUMN letter.send_type IS 'FREE: 하루 1회 무료 발송, PAID: 발송권 사용';

CREATE INDEX ix_letter_sender ON letter (sender_device_id, created_at DESC);
