CREATE TABLE letter_delivery
(
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipient_device_id VARCHAR(100) NOT NULL,
    source_letter_id    BIGINT       NOT NULL REFERENCES letter (id),
    letter_id           BIGINT REFERENCES letter (id),
    status              VARCHAR(10)  NOT NULL DEFAULT 'PENDING',
    scheduled_at        TIMESTAMPTZ  NOT NULL,
    delivered_at        TIMESTAMPTZ,
    read_at             TIMESTAMPTZ,
    saved_at            TIMESTAMPTZ,
    notified_at         TIMESTAMPTZ,
    reminded_at         TIMESTAMPTZ,
    is_deleted          BOOLEAN      NOT NULL DEFAULT false,
    created_at          TIMESTAMPTZ  NOT NULL DEFAULT now(),
    created_by          VARCHAR(100) NOT NULL,
    updated_at          TIMESTAMPTZ,
    updated_by          VARCHAR(100),
    -- 내가 보낸 편지 1통당 받을 수 있는 편지는 1통 (수신 권한 = 발송 횟수)
    CONSTRAINT ux_letter_delivery_source UNIQUE (source_letter_id),
    -- 같은 편지를 두 번 받지 않음 (수신/읽음 목록)
    CONSTRAINT ux_letter_delivery_recipient_letter UNIQUE (recipient_device_id, letter_id),
    CONSTRAINT ck_letter_delivery_status CHECK (
        (status = 'PENDING' AND letter_id IS NULL AND delivered_at IS NULL)
            OR (status = 'DELIVERED' AND letter_id IS NOT NULL AND delivered_at IS NOT NULL)
        )
);
COMMENT ON TABLE letter_delivery IS '편지 수신함 겸 읽음 목록. 편지 발송 시 PENDING 으로 생성되고 scheduled_at 이후 랜덤 편지가 배정됨';
COMMENT ON COLUMN letter_delivery.source_letter_id IS '이 수신 권한을 만들어 준 내가 보낸 편지';
COMMENT ON COLUMN letter_delivery.letter_id IS '배달된(받은) 편지. PENDING 상태에서는 NULL';
COMMENT ON COLUMN letter_delivery.scheduled_at IS '배달 예정 시각 (발송 시각 + 0~3시간 랜덤)';
COMMENT ON COLUMN letter_delivery.saved_at IS '수신자가 받은 편지를 보관한 시각. NULL 이면 보관하지 않음';
COMMENT ON COLUMN letter_delivery.notified_at IS '도착 알림 발송 시각. NULL 이면 아직 보내지 않음';
COMMENT ON COLUMN letter_delivery.reminded_at IS '리마인드 알림 발송 시각 (도착 후 2일간 읽지 않은 경우 1회)';

CREATE INDEX ix_letter_delivery_pending ON letter_delivery (scheduled_at) WHERE status = 'PENDING';
CREATE INDEX ix_letter_delivery_inbox ON letter_delivery (recipient_device_id, delivered_at DESC) WHERE status = 'DELIVERED';
-- 도착 알림 대상: 배달됐지만 알림을 아직 안 보낸 건
CREATE INDEX ix_letter_delivery_notify ON letter_delivery (delivered_at) WHERE status = 'DELIVERED' AND notified_at IS NULL;
-- 리마인드 대상: 배달됐지만 읽지 않았고 리마인드를 아직 안 보낸 건
CREATE INDEX ix_letter_delivery_remind ON letter_delivery (delivered_at) WHERE status = 'DELIVERED' AND read_at IS NULL AND reminded_at IS NULL;
